"""
Нормализация транслитерации и перевода для Deep Past Challenge (Akkadian -> English).

Все правила ниже выведены и проверены на реальных сэмплах данных соревнования
(train.csv, published_texts.csv, test.csv), а не только из документации организаторов —
см. комментарии у каждой функции.
"""
import re
import unicodedata

# --------------------------------------------------------------------------
# 1. Ḫ/ḫ -> H/h
# --------------------------------------------------------------------------
# Подтверждено организаторами явным текстом в Dataset Instructions:
# train (и публикации) содержат Ḫ/ḫ, test содержит только H/h.
# Подтверждено на данных: train_20_rows.csv содержит 62x 'ḫ' и 4x 'Ḫ' в 20 строках.
_HA_MAP = str.maketrans({'Ḫ': 'H', 'ḫ': 'h'})


def normalize_ha(text: str) -> str:
    return text.translate(_HA_MAP)


# --------------------------------------------------------------------------
# 2. ASCII-цифра-индекс -> юникод-подстрочная цифра
# --------------------------------------------------------------------------
# train.csv использует юникод-подстрочные цифры (₄, ₅, ₈ - подтверждено подсчётом).
# published_texts.csv в колонке "transliteration" (clean) почему-то ПОНИЖАЕТ их
# обратно до ASCII (il5-we-da-ku вместо il₅-we-da-ku - подтверждено построчным
# сравнением с transliteration_orig, где юникод есть).
# Приводим всё к конвенции train.csv (юникод), т.к. это основной курируемый ресурс.
_SUBSCRIPT_MAP = str.maketrans('0123456789', '₀₁₂₃₄₅₆₇₈₉')

# цифра сразу после буквы (латиница + акк. диакритика), без разделителя
_DIGIT_AFTER_LETTER = re.compile(
    r'(?<=[a-zA-ZàáâèéêìíîòóôùúûÀÁÂÈÉÊÌÍÎÒÓÔÙÚÛšŠṣṢṭṬḫḪʾ])(\d+)'
)


def ascii_digit_to_subscript(text: str) -> str:
    return _DIGIT_AFTER_LETTER.sub(lambda m: m.group(1).translate(_SUBSCRIPT_MAP), text)


def subscript_to_ascii_digit(text: str) -> str:
    """Обратное преобразование - нужно, если по какой-то причине решите унифицировать
    в другую сторону, либо для сравнения/матчинга текстов из разных источников."""
    rev = str.maketrans('₀₁₂₃₄₅₆₇₈₉', '0123456789')
    return text.translate(rev)


# --------------------------------------------------------------------------
# 3. <big_gap> -> <gap>
# --------------------------------------------------------------------------
# Проверено пользователем на полном датасете: train.csv - 0 вхождений <big_gap>,
# published_texts.csv - всего 4 на ~8000+ строк. Статистический шум, различие
# не имеет практической ценности - унифицируем в один токен.
def unify_gaps(text: str) -> str:
    return text.replace('<big_gap>', '<gap>')


# --------------------------------------------------------------------------
# 4. Полная нормализация транслитерации (пайплайн из шагов 1-3)
# --------------------------------------------------------------------------
def normalize_transliteration(text: str) -> str:
    if text is None:
        return text
    text = unicodedata.normalize('NFC', text)
    text = normalize_ha(text)
    text = ascii_digit_to_subscript(text)
    text = unify_gaps(text)
    text = normalize_parenthetical_determinatives(text)
    text = normalize_broken_tokens(text)
    text = normalize_ligature_equals(text)
    text = re.sub(r'\s+', ' ', text).strip()
    return text


# --------------------------------------------------------------------------
# 5. Чистка перевода: баланс кавычек + скан "чужеродных" юникод-символов
# --------------------------------------------------------------------------
# Подтверждено на train_20_rows.csv: 8/20 строк имеют непарные/висящие двойные
# кавычки (артефакт OCR+LLM-постобработки), в одной строке (009fb838) найдена
# буква иврита ד внутри английского текста ("ofדsilver").
#
# ВАЖНО: Ṣ/ṣ/š/Š/ḫ/ṭ и другие акк. диакритические буквы в переводе - это НЕ
# мусор, это законная передача имён собственных (Ṣilli-Adad и т.п.) - не трогаем.

# Разрешённые юникод-блоки для перевода: базовая латиница + расширенная латиница
# (диакритика для имён) + типографские кавычки/тире/многоточие + наши спецтокены.
#
# ИСПРАВЛЕНО по итогам 1-го прогона на полных данных:
# - U+02B0-02FF (Spacing Modifier Letters) - 'ʾ' (U+02BE), легитимный аккадский
#   глоттальный смычный, был ~80% всех "foreign" находок.
# - \xa0 (NBSP) обрабатывается отдельной заменой на ' ', не репортится.
#
# ИСПРАВЛЕНО по итогам 2-го прогона:
# - U+00A0-00FF расширен целиком (было только 00C0-024F) - ½ (U+00BD) и
#   ¾ (U+00BE) живут в Latin-1 Supplement НИЖЕ 00C0, где раньше была дыра -
#   это легитимные дроби в переводах величин (мины/шекели), не мусор.
# - U+2080-2089 (Subscript digits) и U+2090-209C (Subscript modifier letters,
#   включая ₓ) добавлены - оказалось, что подстрочные цифры/индексы иногда
#   остаются В ПЕРЕВОДЕ как часть непереведённого имени собственного
#   (напр. "Puzur₄-Aššur") - это ожидаемо по инструкции организаторов
#   ("translations usually retain the same proper noun capitalization"),
#   а не мусор.
# - U+2044 (FRACTION SLASH) - типографское "1⁄3" в переводах величин.
#
# ВСЁ ЕЩЁ репортится намеренно (не добавлено в allowlist, т.к. неоднозначно):
# - U+00B4 (ACUTE ACCENT) как отдельный символ - похоже на OCR-артефакт
#   (диакритика "оторвалась" от буквы), не на легитимную типографику.
_ALLOWED_RANGES = [
    (0x0000, 0x007F),   # ASCII
    (0x00A0, 0x00B3),   # Latin-1 Supplement, часть 1 (до ACUTE ACCENT)
    # 0x00B4 (´ ACUTE ACCENT) НАМЕРЕННО не включён - неоднозначный OCR-артефакт,
    # должен репортиться для ручной проверки (см. комментарий выше).
    (0x00B5, 0x024F),   # Latin-1 Supplement часть 2 + Latin Extended A/B
                         # (½ ¾ U+00BD/BE, диакритика имён à š ṣ ṭ ḫ ...)
    (0x02B0, 0x02FF),   # Spacing Modifier Letters (ʾ U+02BE)
    (0x1E00, 0x1EFF),   # Latin Extended Additional (Ṣ, Ṭ, Ḫ и т.п.)
    (0x2013, 0x2014),   # en/em dash
    (0x2018, 0x201F),   # типографские кавычки „ " ' ' и т.п.
    (0x2026, 0x2026),   # …
    (0x2044, 0x2044),   # ⁄ FRACTION SLASH
    (0x2080, 0x2089),   # Subscript digits (в непереведённых именах, напр. Puzur₄-Aššur)
    (0x2090, 0x209C),   # Subscript modifier letters (ₓ - неопределённый индекс знака)
    (0x2150, 0x218F),   # Number Forms (⅚ и другие vulgar fractions)
]


def _is_allowed(ch: str) -> bool:
    cp = ord(ch)
    return any(lo <= cp <= hi for lo, hi in _ALLOWED_RANGES)


def scan_foreign_chars(text: str):
    """Возвращает список (индекс, символ, unicode-имя) для символов вне разрешённых
    диапазонов - кандидатов на OCR-мусор. НЕ удаляет автоматически - для ручной
    проверки, т.к. полностью автоматическое удаление рискованно."""
    found = []
    if text is None:
        return found
    for i, ch in enumerate(text):
        if not _is_allowed(ch):
            try:
                name = unicodedata.name(ch)
            except ValueError:
                name = '<unknown>'
            found.append((i, ch, name))
    return found


def balance_quotes(text: str) -> str:
    """Убирает непарные хвостовые/висящие двойные кавычки на конце строки.
    Консервативный подход: трогаем только явно висящие кавычки на границах
    строки, не пытаемся угадывать парность кавычек в середине текста."""
    if text is None:
        return text
    t = text.strip()
    # убрать серию кавычек/пробелов на конце, если их нечётное/аномальное кол-во
    t = re.sub(r'["\u201c\u201d\u201e\s]+$', lambda m: '' if m.group(0).count('"') != 1
                else m.group(0), t)
    return t.strip()


def normalize_translation(text: str):
    """Возвращает (очищенный_текст, список_найденных_чужеродных_символов).
    Чужеродные символы НЕ удаляются автоматически - только репортятся, решение
    об удалении - на усмотрение того, кто разбирает лог (не все они обязательно
    мусор, лучше проверить глазами хотя бы первые N случаев).

    NBSP (\\xa0) - исключение: заменяется на обычный пробел сразу, не репортится
    как "foreign" (это не мусор для ручной проверки, а тривиальный edge case).

    NFC-нормализация применяется первым делом: часть переводов хранит
    диакритику в NFD-форме (буква + отдельный комбинирующий знак, напр.
    'a' + COMBINING CARON вместо готового 'ǎ') - это не мусор, а другое
    представление того же символа, юникод-каноникализация схлопывает их
    в одно (найдено по факту во 2-м прогоне: COMBINING CARON/MACRON были
    заметной долей "foreign" находок)."""
    if text is None:
        return text, []
    text = unicodedata.normalize('NFC', text)
    text = text.replace('\xa0', ' ')
    foreign = scan_foreign_chars(text)
    cleaned = balance_quotes(text)
    cleaned = re.sub(r'\s+', ' ', cleaned).strip()
    return cleaned, foreign


# --------------------------------------------------------------------------
# 6. Нормализация "сломанных" токенов и вариантов детерминативов
#    (найдено по факту в failed_anchors после первого прогона на полных данных)
# --------------------------------------------------------------------------
# 'x', 'xxx', '…' как ОТДЕЛЬНЫЙ токен - это литеральная запись нечитаемого знака
# (ATF-конвенция). В "чистой" транслитерации документа такой знак уже заменён на
# <gap> нашей же normalize_transliteration, а в first_word_spelling (сыром
# якоре из Sentences_Oare_FirstWord_LinNum.csv) он остаётся как есть - нужно
# применить то же правило к якорю перед сравнением.
_BROKEN_TOKEN = re.compile(r'^[xX]+$')


def normalize_broken_tokens(text: str) -> str:
    tokens = text.split()
    out = [
        '<gap>' if (t == '…' or _BROKEN_TOKEN.match(t)) else t
        for t in tokens
    ]
    return ' '.join(out)


# Круглые скобки для детерминативов: Sentences_Oare_FirstWord_LinNum.csv
# использует (TÚG), (d) и т.п., тогда как published_texts.csv (clean) - только
# фигурные {TÚG}, {d}. Унифицируем в фигурные (конвенция train.csv/published).
# Регулярка глобальная (не только детерминативы) - на транслитерации круглые
# скобки больше ни для чего не используются (после удаления scribal-нотаций).
_PAREN_DETERMINATIVE = re.compile(r'\(([^()]+)\)')


def normalize_parenthetical_determinatives(text: str) -> str:
    return _PAREN_DETERMINATIVE.sub(r'{\1}', text)


# --------------------------------------------------------------------------
# 7. '=' в якорях типа 'i-dí=(d)UTU', 'PUZUR₄=(d)UTU'
# --------------------------------------------------------------------------
# Найдено по факту во 2-м прогоне (extraction_report.txt): Sentences_Oare_
# FirstWord_LinNum.csv записывает составные имена через '=' (похоже на
# внутреннюю нотацию границы леммы в OARE-базе), а в самой транслитерации
# документа (published_texts.csv) такого разделителя нет - просто дефис,
# как у обычных слогов. 5+ вхождений на 68 промахов - системный паттерн,
# не единичный случай.
def normalize_ligature_equals(text: str) -> str:
    return text.replace('=', '-')
